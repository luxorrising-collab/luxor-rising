// Builds lib/image-credits.generated.ts from docs/image-credits/<slug>.md.
// Each credits file holds a markdown table: File | Original | Author | Licence | Source.
// The product page shows a small "Photo credits" line for every image whose
// licence needs attribution (CC BY / CC BY-SA). Public domain and CC0 are listed
// in the docs but need no credit on the page.
//
// Run after adding or changing open-licence photos:  node scripts/build-image-credits.mjs
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/(\w:)/, "$1")), "..");
const dir = path.join(root, "docs", "image-credits");
const out = path.join(root, "lib", "image-credits.generated.ts");

const credits = {};
for (const file of fs.readdirSync(dir).filter((f) => f.endsWith(".md")).sort()) {
  const slug = file.replace(/\.md$/, "");
  const rows = fs
    .readFileSync(path.join(dir, file), "utf8")
    .split(/\r?\n/)
    .filter((l) => l.startsWith("|") && /\|\s*https?:\/\/\S+\s*\|\s*$/.test(l))
    .map((l) => l.split("|").slice(1, -1).map((c) => c.trim()))
    .map(([image, , author, licence, source]) => ({ image, author, licence, source }))
    .filter((r) => /\bCC BY\b/i.test(r.licence));
  if (rows.length) credits[slug] = rows;
}

const body = `// Generated by scripts/build-image-credits.mjs from docs/image-credits/*.md. Do not edit by hand.
export type ImageCredit = { image: string; author: string; licence: string; source: string };
export const IMAGE_CREDITS: Record<string, ImageCredit[]> = ${JSON.stringify(credits, null, 2)};
`;
fs.writeFileSync(out, body);
console.log(`Wrote ${Object.keys(credits).length} products, ${Object.values(credits).flat().length} credited photos → ${path.relative(root, out)}`);
